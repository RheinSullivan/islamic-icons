// Build catalog from assets/icons and write to:
//   - assets/catalog.json (source of truth)
//   - catalog.js + catalog.d.ts (bundled into published package)
//   - web-docs/src/lib/catalog.generated.ts (Svelte data source)
import { createHash } from 'node:crypto';
import { readdir, writeFile, mkdir, readFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(new URL('.', import.meta.url)));
const repoRoot = join(root, '..');
const iconRoot = join(root, 'assets', 'icons');

const title = (name) =>
	String(name)
		.replace(/[-_]/g, ' ')
		.replace(/([a-z])([A-Z])/g, '$1 $2')
		.replace(/\b\w/g, (c) => c.toUpperCase());

const sourceLabels = {
	community: 'Community / Rhein Sullivan',
	'svg-repo': 'SVG Repo',
	'mary-akveo': 'Mary Akveo',
	'google-material': 'Google Material Icons',
	'community-upload': 'Community Upload'
};

const variants = ['fill', 'outline', 'color', 'original', 'alternate'];

async function fileExists(path) {
	try {
		const f = await readFile(path);
		return f.length > 0;
	} catch {
		return false;
	}
}

async function hashFile(path) {
	const buf = await readFile(path);
	return createHash('sha256').update(buf).digest('hex');
}

const aliases = JSON.parse(await readFile(join(root, 'assets', 'icon-aliases.json'), 'utf8'));
const external = JSON.parse(await readFile(join(root, 'assets', 'external-sources.json'), 'utf8'));

const catalog = [];
const fingerprints = new Map();

for (const cat of await readdir(iconRoot, { withFileTypes: true })) {
	if (!cat.isDirectory()) continue;
	const catDir = join(iconRoot, cat.name);
	for (const item of await readdir(catDir, { withFileTypes: true })) {
		if (!item.isDirectory()) continue;
		const name = item.name;
		const dir = join(catDir, name);
		const entry = { name, category: cat.name, title: title(name), sources: [] };

		const communityVariants = [];
		for (const v of variants) {
			if (await fileExists(join(dir, `${v}.svg`))) communityVariants.push(v);
		}
		if (communityVariants.length)
			entry.sources.push({
				id: 'community',
				label: sourceLabels.community,
				variants: communityVariants
			});

		const sourceRoot = join(dir, 'sources');
		try {
			for (const sourceDir of await readdir(sourceRoot, { withFileTypes: true })) {
				if (!sourceDir.isDirectory()) continue;
				const sourceDirPath = join(sourceRoot, sourceDir.name);
				const sourceVariants = [];
				for (const v of variants) {
					if (await fileExists(join(sourceDirPath, `${v}.svg`))) sourceVariants.push(v);
				}
				if (sourceVariants.length)
					entry.sources.push({
						id: sourceDir.name,
						label: sourceLabels[sourceDir.name] || title(sourceDir.name),
						variants: sourceVariants
					});
			}
		} catch (err) {
			if (err.code !== 'ENOENT') throw err;
		}

		if (!entry.sources.length) continue;

		const itemAliases = aliases
			.filter((a) => a.category === cat.name && a.canonical === name)
			.map((a) => a.name);
		if (itemAliases.length) entry.aliases = itemAliases.sort();

		const files = [];
		const walk = async (d) => {
			for (const e of await readdir(d, { withFileTypes: true })) {
				const p = join(d, e.name);
				if (e.isDirectory()) await walk(p);
				else if (e.name.endsWith('.svg')) files.push(p);
			}
		};
		await walk(dir);
		files.sort();
		const fingerprint = (await Promise.all(files.map(hashFile))).join(':');
		if (fingerprints.has(fingerprint))
			throw new Error(
				`Duplicate logical icon detected: ${cat.name}/${name} duplicates ${fingerprints.get(fingerprint)}`
			);
		fingerprints.set(fingerprint, `${cat.name}/${name}`);
		catalog.push(entry);
	}
}

catalog.sort((a, b) => a.category.localeCompare(b.category) || a.title.localeCompare(b.title));

// 1. Write assets/catalog.json
await writeFile(
	join(root, 'assets', 'catalog.json'),
	JSON.stringify(catalog, null, 2) + '\n',
	'utf8'
);

// 2. Write the published package's catalog.js
await mkdir(join(root, 'icons'), { recursive: true });
await writeFile(
	join(root, 'catalog.js'),
	`// Generated by ` + '`bun run icons:catalog`' + `\nexport const catalog = ${JSON.stringify(catalog, null, 2)};\nexport const sources = ${JSON.stringify(external, null, 2)};\nexport const metadata = ${JSON.stringify(JSON.parse(await readFile(join(root, 'assets', 'metadata.json'), 'utf8')), null, 2)};\n`,
	'utf8'
);

await writeFile(
	join(root, 'catalog.d.ts'),
	`// Generated by ` + '`bun run icons:catalog`' + `\nimport type { CatalogItem, SourceItem, LibraryMetadata } from './types';\nexport declare const catalog: CatalogItem[];\nexport declare const sources: SourceItem[];\nexport declare const metadata: LibraryMetadata;\n`,
	'utf8'
);

// 3. Write Svelte web-docs source
const webDocsLib = join(repoRoot, 'web-docs', 'src', 'lib');
await mkdir(webDocsLib, { recursive: true });
await writeFile(
	join(webDocsLib, 'catalog.generated.ts'),
	`// Generated by bun run icons:catalog. Do not edit.\nimport type { CatalogItem, SourceItem, LibraryMetadata } from './types';\nexport const catalog: CatalogItem[] = ${JSON.stringify(catalog)};\nexport const sources: SourceItem[] = ${JSON.stringify(external)};\nexport const metadata: LibraryMetadata = ${JSON.stringify(JSON.parse(await readFile(join(root, 'assets', 'metadata.json'), 'utf8')))};\n`,
	'utf8'
);

console.log(
	`Cataloged ${catalog.length} logical icons with source-aware variants and duplicate protection.`
);