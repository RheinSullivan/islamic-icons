// Build the published package layout under library/.
// Run AFTER build-catalog.mjs.
//   - icons/<category>/<icon>/<variant>.svg copied from assets/icons/...
//   - icons/<category>/<icon>/sources/<sourceId>/<variant>.svg copied
//   - icons/<category>/index.js exports each icon's variants as URLs
//   - categories.js, metadata.js, index.js at root
//   - sources/ folder copies JSON for third-party license info
import { cp, mkdir, rm, writeFile, readFile, readdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(new URL('.', import.meta.url)));
const iconRoot = join(root, 'assets', 'icons');
const assetsSource = join(root, 'assets');

const catalog = JSON.parse(await readFile(join(root, 'assets', 'catalog.json'), 'utf8'));
const aliases = JSON.parse(await readFile(join(root, 'assets', 'icon-aliases.json'), 'utf8'));
const external = JSON.parse(await readFile(join(root, 'assets', 'external-sources.json'), 'utf8'));
const metadata = JSON.parse(await readFile(join(root, 'assets', 'metadata.json'), 'utf8'));

const ident = (s) =>
	String(s)
		.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
		.replace(/[^A-Za-z0-9_$]/g, '');

const title = (s) =>
	String(s)
		.replace(/[-_]/g, ' ')
		.replace(/([a-z])([A-Z])/g, '$1 $2')
		.replace(/\b\w/g, (c) => c.toUpperCase());

const categories = [...new Set(catalog.map((i) => i.category))].sort();

// 1. Clear & repopulate icons/ directory
await rm(join(root, 'icons'), { recursive: true, force: true });
await mkdir(join(root, 'icons'), { recursive: true });
await cp(iconRoot, join(root, 'icons'), { recursive: true });

// 2. Clear & repopulate sources/ directory
await rm(join(root, 'sources'), { recursive: true, force: true });
await mkdir(join(root, 'sources'), { recursive: true });
for (const item of external) {
	const safe = String(item.name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
	await writeFile(
		join(root, 'sources', `${safe}.json`),
		JSON.stringify(item, null, 2) + '\n',
		'utf8'
	);
}

// 3. Copy logo
await cp(join(assetsSource, 'logo-islamic-icons.svg'), join(root, 'logo-islamic-icons.svg'));

// 4. Build per-category index.js files exposing URLs
const variantSuffix = (variant) => {
	if (variant === 'fill') return '';
	if (variant === 'outline') return 'Outline';
	if (variant === 'color') return 'Color';
	if (variant === 'alternate') return 'Alternate';
	if (variant === 'original') return 'Original';
	return variant[0].toUpperCase() + variant.slice(1);
};

const pathForSource = (item, variant, source) => {
	if (source.id === 'community') return `./icons/${item.category}/${item.name}/${variant}.svg`;
	return `./icons/${item.category}/${item.name}/sources/${source.id}/${variant}.svg`;
};

for (const category of categories) {
	const items = catalog.filter((i) => i.category === category);
	const lines = [`// Generated by bun run icons:package`, ''];
	const exports = [];

	for (const item of items) {
		const base = ident(item.name);
		lines.push(`// ${item.title}`);
		for (const variant of ['fill', 'outline', 'color', 'original', 'alternate']) {
			let found = null;
			for (const source of item.sources) {
				if (source.variants?.includes(variant)) {
					found = { source, path: pathForSource(item, variant, source) };
					break;
				}
			}
			if (!found) continue;
			const name = `${base}${variantSuffix(variant)}`;
			lines.push(`export const ${name} = new URL(${JSON.stringify(found.path)}, import.meta.url).href;`);
			exports.push(name);
		}
		lines.push('');
	}

	// Aliases
	for (const alias of aliases.filter((a) => a.category === category)) {
		const canonical = ident(alias.canonical);
		const name = ident(alias.name);
		lines.push(`export const ${name} = ${canonical};`);
		lines.push(`export const ${name}Outline = ${canonical}Outline;`);
		lines.push(`export const ${name}Color = ${canonical}Color;`);
	}

	await writeFile(join(root, 'icons', `${category}.js`), lines.join('\n') + '\n', 'utf8');
}

// 5. categories.js - list of all categories with metadata
const categoryList = categories.map((c) => {
	const count = catalog.filter((i) => i.category === c).length;
	return { id: c, name: title(c), count };
});
await writeFile(
	join(root, 'categories.js'),
	`// Generated by bun run icons:package\nexport const categories = ${JSON.stringify(categoryList, null, 2)};\n`,
	'utf8'
);
await writeFile(
	join(root, 'categories.d.ts'),
	`// Generated by bun run icons:package\nimport type { CategoryEntry } from './types';\nexport declare const categories: CategoryEntry[];\n`,
	'utf8'
);

// 6. metadata.js
await writeFile(
	join(root, 'metadata.js'),
	`// Generated by bun run icons:package\nexport const metadata = ${JSON.stringify(metadata, null, 2)};\n`,
	'utf8'
);
await writeFile(
	join(root, 'metadata.d.ts'),
	`// Generated by bun run icons:package\nimport type { LibraryMetadata } from './types';\nexport declare const metadata: LibraryMetadata;\n`,
	'utf8'
);

// 7. index.js - top-level entrypoint
const indexExports = [
	`export { catalog, sources, metadata } from './catalog.js';`,
	`export { categories } from './categories.js';`,
	`export { metadata as library } from './metadata.js';`
];
await writeFile(join(root, 'index.js'), indexExports.join('\n') + '\n', 'utf8');
await writeFile(
	join(root, 'index.d.ts'),
	`export { catalog, sources, metadata, categories, library } from './catalog.js';\nexport type { CatalogItem, SourceItem, LibraryMetadata, CategoryEntry } from './types.js';\n`,
	'utf8'
);

// 8. types.d.ts
await writeFile(
	join(root, 'types.d.ts'),
	`export type CatalogItem = {
  name: string;
  category: string;
  title: string;
  aliases?: string[];
  sources: Array<{
    id: string;
    label: string;
    variants?: string[];
    solidVariants?: string[];
  }>;
};

export type SourceItem = {
  name: string;
  kind: string;
  discoveredVia: string;
  source: string;
  license?: string;
  licensePolicy: string;
  examples?: Array<{ name: string; url: string; license: string }>;
};

export type LibraryMetadata = {
  name: string;
  version: string;
  logo: string;
  description: string;
  author: string;
  runtime: string;
  css: string;
  assetModel: string;
  documentation: string;
  iconCount: number;
  sourceArchive: string;
  importedIconPolicy: string;
  repository?: string;
  homepage?: string;
  license?: string;
};

export type CategoryEntry = {
  id: string;
  name: string;
  count: number;
};
`,
	'utf8'
);

// 9. README for the published package
const readme = `# Islamic Icons

A framework-agnostic Islamic SVG and WebP icon library for the modern web.

The collection is organized around semantic categories and ships with three style variants (fill, outline, color) per logical icon when the source artwork permits. Every icon is a local asset; no runtime fetch is required to render.

## Installation

\`\`\`bash
bun add islamic-icons
npm install islamic-icons
pnpm add islamic-icons
yarn add islamic-icons
\`\`\`

For Deno, use the npm compatibility specifier:

\`\`\`bash
deno add npm:islamic-icons
\`\`\`

## Usage

### Native HTML

\`\`\`html
<img src="/assets/icons/mosque/mosque/fill.svg" alt="Mosque" width="24" height="24" />
\`\`\`

### JavaScript / TypeScript

\`\`\`ts
import { categories, catalog, metadata } from 'islamic-icons';
import { mosque, mosqueOutline, mosqueColor } from 'islamic-icons/icons/mosque.js';

console.log(categories);
console.log(mosque);     // URL string to fill variant
console.log(mosqueOutline);
console.log(mosqueColor);
\`\`\`

### React / JSX

\`\`\`jsx
import { mosque } from 'islamic-icons/icons/mosque.js';

export function MosqueIcon() {
	return <img src={mosque} alt="Mosque" width={24} height={24} />;
}
\`\`\`

### Vue

\`\`\`vue
<script setup lang="ts">
import { mosque } from 'islamic-icons/icons/mosque.js';
</script>

<template>
	<img :src="mosque" alt="Mosque" width="24" height="24" />
</template>
\`\`\`

### Svelte / SvelteKit

\`\`\`svelte
<script lang="ts">
	import { mosque } from 'islamic-icons/icons/mosque.js';
</script>

<img src={mosque} alt="Mosque" width="24" height="24" />
\`\`\`

### Astro

\`\`\`astro
---
import { mosque } from 'islamic-icons/icons/mosque.js';
---
<img src={mosque} alt="Mosque" width="24" height="24" />
\`\`\`

### Aliases

Several canonical icons have aliases for convenience:

\`\`\`ts
import { allah, quran, tasbih, qibla, muslim } from 'islamic-icons/icons/god.js';
// or any of the relevant category files
\`\`\`

## Exports

| Path | Description |
| --- | --- |
| \`islamic-icons\` | \`catalog\`, \`sources\`, \`metadata\`, \`categories\`, \`library\` |
| \`islamic-icons/metadata\` | \`metadata\` (name, version, icon count, etc.) |
| \`islamic-icons/categories\` | \`categories\` array with id, name, count |
| \`islamic-icons/icons/<category>\` | Per-icon URL exports for \`<category>\` |
| \`islamic-icons/icons/<category>.js\` | Same as above (CJS-friendly) |
| \`islamic-icons/sources/<slug>.json\` | License & attribution metadata per external source |

## License

MIT © ${metadata.author}
`;
await writeFile(join(root, 'README.md'), readme, 'utf8');

// 10. Copy LICENSE, NOTICE, ATTRIBUTION
await cp(join(root, 'LICENSE'), join(root, 'LICENSE'));
await cp(join(root, 'NOTICE.md'), join(root, 'NOTICE.md'));
await cp(join(root, 'ATTRIBUTION.md'), join(root, 'ATTRIBUTION.md'));

console.log(
	`Packaged ${catalog.length} logical icons across ${categories.length} categories with metadata, categories, sources, and per-category icon exports.`
);