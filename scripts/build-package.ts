// Build the published package layout under library/.
// Run AFTER build-catalog.ts.
//   - icons/<category>/<icon>/<variant>.svg copied from assets/icons/...
//   - icons/<category>/<icon>/sources/<sourceId>/<variant>.svg copied
//   - icons/<category>/index.js exports each icon's variants as URLs
//   - categories.js, metadata.js, index.js at root
//   - sources/ folder copies JSON for third-party license info
import { cp, mkdir, rm, writeFile, readFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const libraryRoot = dirname(fileURLToPath(new URL('.', import.meta.url)));
const iconRoot = join(libraryRoot, 'assets', 'icons');
const assetsSource = join(libraryRoot, 'assets');

interface CatalogItem {
	name: string;
	category: string;
	title: string;
	aliases?: string[];
	sources: Array<{
		id: string;
		label: string;
		variants?: string[];
	}>;
}

interface AliasItem {
	name: string;
	canonical: string;
	category: string;
}

interface ExternalSourceItem {
	name: string;
	id?: string;
	[key: string]: unknown;
}

const catalog: CatalogItem[] = JSON.parse(await readFile(join(libraryRoot, 'assets', 'catalog.json'), 'utf8'));
const aliases: AliasItem[] = JSON.parse(await readFile(join(libraryRoot, 'assets', 'icon-aliases.json'), 'utf8'));
const externalSources: ExternalSourceItem[] = JSON.parse(await readFile(join(libraryRoot, 'assets', 'external-sources.json'), 'utf8'));
const metadata = JSON.parse(await readFile(join(libraryRoot, 'assets', 'metadata.json'), 'utf8'));

const createIdentifierName = (rawIdentifier: string): string =>
	String(rawIdentifier)
		.replace(/-([a-z])/g, (_, matchedCharacter: string) => matchedCharacter.toUpperCase())
		.replace(/[^A-Za-z0-9_$]/g, '');

const formatCategoryTitle = (rawTitle: string): string =>
	String(rawTitle)
		.replace(/[-_]/g, ' ')
		.replace(/([a-z])([A-Z])/g, '$1 $2')
		.replace(/\b\w/g, (matchedCharacter: string) => matchedCharacter.toUpperCase());

const uniqueCategories: string[] = [...new Set(catalog.map((catalogItem: CatalogItem) => catalogItem.category))].sort();

// 1. Clear & repopulate icons/ directory
await rm(join(libraryRoot, 'icons'), { recursive: true, force: true });
await mkdir(join(libraryRoot, 'icons'), { recursive: true });
await cp(iconRoot, join(libraryRoot, 'icons'), { recursive: true });

// 2. Clear & repopulate sources/ directory
await rm(join(libraryRoot, 'sources'), { recursive: true, force: true });
await mkdir(join(libraryRoot, 'sources'), { recursive: true });
for (const sourceItem of externalSources) {
	const sanitizedSlug = String(sourceItem.name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
	await writeFile(
		join(libraryRoot, 'sources', `${sanitizedSlug}.json`),
		JSON.stringify(sourceItem, null, 2) + '\n',
		'utf8'
	);
}

// 3. Copy logo
await cp(join(assetsSource, 'logo-atsarul-mujahidin.svg'), join(libraryRoot, 'logo-atsarul-mujahidin.svg'));

// 4. Build per-category index.js files exposing URLs
const getVariantSuffix = (variantName: string): string => {
	if (variantName === 'fill') return '';
	if (variantName === 'outline') return 'Outline';
	if (variantName === 'color') return 'Color';
	if (variantName === 'alternate') return 'Alternate';
	if (variantName === 'original') return 'Original';
	return variantName.charAt(0).toUpperCase() + variantName.slice(1);
};

const resolveSourcePath = (catalogItem: CatalogItem, variantName: string, sourceCandidate: { id: string }): string => {
	if (sourceCandidate.id === 'community') {
		return `./icons/${catalogItem.category}/${catalogItem.name}/${variantName}.svg`;
	}
	return `./icons/${catalogItem.category}/${catalogItem.name}/sources/${sourceCandidate.id}/${variantName}.svg`;
};

for (const categoryName of uniqueCategories) {
	const categoryItems = catalog.filter((catalogItem: CatalogItem) => catalogItem.category === categoryName);
	const codeLines: string[] = ['// Generated by bun run icons:package', ''];

	for (const item of categoryItems) {
		const baseIdentifier = createIdentifierName(item.name);
		codeLines.push(`// ${item.title}`);
		for (const variantOption of ['fill', 'outline', 'color', 'original', 'alternate']) {
			let matchedSource: { source: { id: string }; path: string } | null = null;
			for (const sourceItem of item.sources) {
				if (sourceItem.variants?.includes(variantOption)) {
					matchedSource = { source: sourceItem, path: resolveSourcePath(item, variantOption, sourceItem) };
					break;
				}
			}
			if (!matchedSource) continue;
			const exportedConstantName = `${baseIdentifier}${getVariantSuffix(variantOption)}`;
			codeLines.push(`export const ${exportedConstantName} = new URL(${JSON.stringify(matchedSource.path)}, import.meta.url).href;`);
		}
		codeLines.push('');
	}

	// Aliases
	for (const aliasItem of aliases.filter((aliasCandidate: AliasItem) => aliasCandidate.category === categoryName)) {
		const canonicalIdentifier = createIdentifierName(aliasItem.canonical);
		const aliasIdentifier = createIdentifierName(aliasItem.name);
		codeLines.push(`export const ${aliasIdentifier} = ${canonicalIdentifier};`);
		codeLines.push(`export const ${aliasIdentifier}Outline = ${canonicalIdentifier}Outline;`);
		codeLines.push(`export const ${aliasIdentifier}Color = ${canonicalIdentifier}Color;`);
	}

	await writeFile(join(libraryRoot, 'icons', `${categoryName}.js`), codeLines.join('\n') + '\n', 'utf8');
}

// 5. categories.js - list of all categories with metadata
const categoryList = uniqueCategories.map((categoryName: string) => {
	const iconCount = catalog.filter((catalogItem: CatalogItem) => catalogItem.category === categoryName).length;
	return { id: categoryName, name: formatCategoryTitle(categoryName), count: iconCount };
});
await writeFile(
	join(libraryRoot, 'categories.js'),
	`// Generated by bun run icons:package\nexport const categories = ${JSON.stringify(categoryList, null, 2)};\n`,
	'utf8'
);
await writeFile(
	join(libraryRoot, 'categories.d.ts'),
	`// Generated by bun run icons:package\nimport type { CategoryEntry } from './types';\nexport declare const categories: CategoryEntry[];\n`,
	'utf8'
);

// 6. metadata.js
await writeFile(
	join(libraryRoot, 'metadata.js'),
	`// Generated by bun run icons:package\nexport const metadata = ${JSON.stringify(metadata, null, 2)};\n`,
	'utf8'
);
await writeFile(
	join(libraryRoot, 'metadata.d.ts'),
	`// Generated by bun run icons:package\nimport type { LibraryMetadata } from './types';\nexport declare const metadata: LibraryMetadata;\n`,
	'utf8'
);

// 7. index.js - top-level entrypoint
const indexExports: string[] = [
	`export { catalog, sources, metadata } from './catalog.js';`,
	`export { categories } from './categories.js';`,
	`export { metadata as library } from './metadata.js';`
];
await writeFile(join(libraryRoot, 'index.js'), indexExports.join('\n') + '\n', 'utf8');
await writeFile(
	join(libraryRoot, 'index.d.ts'),
	`export { catalog, sources, metadata, categories, library } from './catalog.js';\nexport type { CatalogItem, SourceItem, LibraryMetadata, CategoryEntry } from './types.js';\n`,
	'utf8'
);

// 8. types.d.ts
await writeFile(
	join(libraryRoot, 'types.d.ts'),
	`export type CatalogItem = {
  name: string;
  category: string;
  title: string;
  aliases?: string[];
  sources: Array<{
    id: string;
    label: string;
    variants?: string[];
    solidVariants?: string[];
  }>;
};

export type SourceItem = {
  name: string;
  kind: string;
  discoveredVia: string;
  source: string;
  license?: string;
  licensePolicy: string;
  examples?: Array<{ name: string; url: string; license: string }>;
};

export type LibraryMetadata = {
  name: string;
  version: string;
  logo: string;
  description: string;
  author: string;
  runtime: string;
  css: string;
  assetModel: string;
  documentation: string;
  iconCount: number;
  sourceArchive: string;
  importedIconPolicy: string;
  repository?: string;
  homepage?: string;
  license?: string;
};

export type CategoryEntry = {
  id: string;
  name: string;
  count: number;
};
`,
	'utf8'
);

console.log(
	`✓ Packaged ${catalog.length} logical icons across ${uniqueCategories.length} categories with metadata, categories, sources, and per-category icon exports.`
);